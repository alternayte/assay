// Command authschema writes the auth-all migration units that Assay applies to
// a directory, so that sqlc can read the auth-all tables. The server applies
// the same units from the library at start.
package main

import (
	"context"
	"fmt"
	"log/slog"
	"os"
	"path/filepath"

	"github.com/alternayte/auth-all/migrations"
	"github.com/alternayte/auth-all/schema"
	"github.com/jackc/pgx/v5/pgxpool"

	"github.com/alternayte/assay/internal/auth"
)

func main() {
	if err := run(); err != nil {
		fmt.Fprintln(os.Stderr, "authschema:", err)
		os.Exit(1)
	}
}

func run() error {
	if len(os.Args) != 2 {
		return fmt.Errorf("usage: authschema <dir>")
	}
	dir := os.Args[1]
	// The pool never connects. auth.New needs it only to build the store.
	pool, err := pgxpool.New(context.Background(), "postgres://127.0.0.1:1/none")
	if err != nil {
		return err
	}
	defer pool.Close()
	a, err := auth.New(pool, "http://localhost:8080", slog.New(slog.DiscardHandler), auth.Options{})
	if err != nil {
		return err
	}
	files, err := a.ExportMigrations(schema.Postgres, migrations.Goose)
	if err != nil {
		return err
	}
	if err := os.RemoveAll(dir); err != nil {
		return err
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return err
	}
	for _, f := range files {
		content := "-- Code generated by tools/authschema. DO NOT EDIT.\n\n" + f.Content
		if err := os.WriteFile(filepath.Join(dir, f.Name), []byte(content), 0o644); err != nil {
			return err
		}
	}
	return nil
}
